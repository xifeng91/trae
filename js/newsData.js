  /**
   * 保存到 LocalStorage
   */
  saveToStorage(data) {
    try {
      localStorage.setItem(this.STORAGE_KEY, JSON.stringify(data));
      localStorage.setItem(this.CACHE_KEY, Date.now().toString());
      return true;
    } catch (e) {
      console.warn('LocalStorage 保存失败:', e);
      return false;
    }
  },

  /**
   * 从 LocalStorage 加载
   */
  loadFromStorage() {
    try {
      const data = localStorage.getItem(this.STORAGE_KEY);
      if (!data) return null;
      return JSON.parse(data);
    } catch (e) {
      console.warn('LocalStorage 读取失败:', e);
      return null;
    }
  },

  /**
   * 获取或生成新闻
   * 会检查版本号，数据格式变更时自动刷新
   */
  getNews() {
    // 检查是否有缓存且是今天的数据
    const cached = this.loadFromStorage();
    const today = new Date();
    const todayStr = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`;

    // 版本不匹配或非当天数据 → 重新生成
    if (cached && cached.date === todayStr && cached.version === this.VERSION) {
      return cached;
    }

    // 生成新数据
    const freshData = this.generateTodayNews();
    freshData.version = this.VERSION;
    this.saveToStorage(freshData);
    return freshData;
  },

  /**
   * 手动强制刷新
   */
  refresh() {
    const freshData = this.generateTodayNews();
    freshData.version = this.VERSION;
    this.saveToStorage(freshData);
    return freshData;
  },

  /**
   * 获取某分类的新闻
   */
  getByCategory(data, category) {
    if (category === '全部') return data.news;
    return data.news.filter(item => item.category === category);
  },

  /**
   * 检查是否需要自动更新（每天早上7点）
   */
  shouldAutoRefresh() {
    const lastUpdate = localStorage.getItem(this.CACHE_KEY);
    if (!lastUpdate) return true;

    const lastDate = new Date(parseInt(lastUpdate));
    const now = new Date();

    // 如果上次更新不是今天，则需要更新
    if (lastDate.toDateString() !== now.toDateString()) {
      // 在当前时间 >= 7:00 时更新
      const hour = now.getHours();
      return hour >= 7;
    }
    return false;
  }
